#!/usr/bin/env bash
set -euo pipefail

SCRIPTS_DIR=${NOBOOM_ROOT_DIR}/scripts

# Helper: treat env var as boolean (1=true, 0/empty/unset=false)
is_one() {
  local name="$1"
  local val="${!name:-0}"
  [[ "$val" == "1" ]]
}

###############################################################################
# 1) Parse arguments: <HEAD_IP> [WORKER_IP ...] -- [run_tune.py args ...]
###############################################################################
if [ "$#" -lt 1 ]; then
  echo "Usage: $0 <head_ip> [worker_ip ...]" >&2
  exit 1
fi

HEAD_IP="$1"
shift

WORKER_IPS=("$@")

echo "[INFO] HEAD_IP=${HEAD_IP}"
echo "[INFO] Worker IPs: ${WORKER_IPS[*]:-<none>}"

echo "[INFO] Running remote setup on $(hostname)"

echo "[INFO] Using Postgres user=${POSTGRES_USER:-<not-set>}"

###############################################################################
# 5) Create directories
###############################################################################

###############################################################################
# 6) Create pg_hba.conf allowing only localhost, HEAD_IP, worker IPs
###############################################################################
PG_HBA_PATH="${SCRIPTS_DIR}/pg_hba.conf"

if is_one NOBOOM_SKIP_PG_HBA; then
  echo "[SKIP] Skipping pg_hba.conf generation because NOBOOM_SKIP_PG_HBA=1."
else
  echo "[INFO] Writing ${PG_HBA_PATH}"

  cat >"${PG_HBA_PATH}" <<EOF
# Auto-generated by setup_noboom_remote.sh

# TYPE  DATABASE        USER            ADDRESS                 METHOD
local   all             all                                     scram-sha-256
host    all             all             127.0.0.1/32            scram-sha-256
host    all             all             ${HEAD_IP}/32           scram-sha-256
EOF

  for ip in "${WORKER_IPS[@]}"; do
    echo "host    all             all             ${ip}/32            scram-sha-256" >> "${PG_HBA_PATH}"
  done

  echo "host    all             all             0.0.0.0/0           reject" >> "${PG_HBA_PATH}"

  echo "[INFO] pg_hba.conf content:"
  cat "${PG_HBA_PATH}"
fi

###############################################################################
# 8) Stop any existing containers
###############################################################################
if is_one NOBOOM_SKIP_DOCKER_CLEANUP; then
  echo "[SKIP] Skipping Docker cleanup because NOBOOM_SKIP_DOCKER_CLEANUP=1."
else
  echo "[INFO] Stopping/removing old containers (if any)"
  docker rm -f noboom-postgres noboom-mlflow noboom-seaweedfs seaweed_vacuum 2>/dev/null || true
  rm -rf "${HOME}/postgres" 2>/dev/null || sudo rm -rf "${HOME}/postgres" 2>/dev/null || true
  rm -rf "${HOME}/experiment_data" 2>/dev/null || sudo rm -rf "${HOME}/experiment_data" 2>/dev/null || true
fi

###############################################################################
# Helper: determine docker compose command
###############################################################################
choose_compose_cmd() {
  if command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
    echo "docker compose"
  elif command -v docker-compose >/dev/null 2>&1; then
    echo "docker-compose"
  else
    echo ""
  fi
}

###############################################################################
# 9) Start Postgres + MLflow via docker compose
###############################################################################
if is_one NOBOOM_SKIP_COMPOSE_UP; then
  echo "[SKIP] Skipping docker compose up because NOBOOM_SKIP_COMPOSE_UP=1."
else
  DC="$(choose_compose_cmd)"
  if [[ -z "${DC}" ]]; then
    echo "[ERROR] Neither 'docker compose' nor 'docker-compose' found in PATH. Run setup_docker_for_cloud.sh first." >&2
    exit 1
  fi

  COMPOSE_FILE="${SCRIPTS_DIR}/docker-compose.yaml"
  if [ ! -f "${COMPOSE_FILE}" ]; then
    echo "[ERROR] docker-compose.yaml not found at ${COMPOSE_FILE}" >&2
    exit 1
  fi

  echo "[INFO] Using compose file: ${COMPOSE_FILE}"
  echo "[INFO] Exporting HEAD_IP for docker-compose interpolation"
  export HEAD_IP

  #sudo rm -rf ${NOBOOM_ROOT_DIR}/postgres

  echo "[INFO] Bringing up SeaweedFS, Postgres and MLflow..."
  ${DC} -f "${COMPOSE_FILE}" up --pull always -d
fi
